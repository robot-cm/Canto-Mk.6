/* Persist last file + reading position (permille 0..10000) + FM anchor +
 * FM expanded dirs. Format: "<path>\n<pos>\n<fm_anchor>\n<exp>\n"; a bare-path
 * line is the legacy format (pos=0); missing line 3 means "no FM position to
 * restore"; line 4 is "p1|p2|p3" (newest last, up to TH_FM_EXP_MAX). */
/* 序列化并写入历史文件(path 可为 NULL,此时其余行留空)。
 * Format: "<path>\n<pos>\n<fm_anchor>\n<exp>\n",exp 为 "p1|p2|p3"
 * (最新在行尾,最多 TH_FM_EXP_MAX 个)。 */
static void _fm_hist_write(const char *path, uint32_t pos)
{
    eos_storage_mkdir_recursive(TH_HIST_DIR);
    char buf[EOS_FS_PATH_MAX * 6 + 32];
    int n = snprintf(buf, sizeof(buf), "%s\n%u\n%s\n",
                     path ? path : "", (unsigned)pos, s_fm_anchor);
    /* line 4: 最近展开的文件夹(最多 3 个,| 分隔,行尾最新) */
    for (int i = 0; i < s_fm_exp_count && n > 0 && n < (int)sizeof(buf); i++) {
        n += snprintf(buf + n, sizeof(buf) - (size_t)n, "%s%s",
                      i ? "|" : "", s_fm_exp[i]);
    }
    if (n < 0) n = 0;
    if ((size_t)n > sizeof(buf)) n = (int)sizeof(buf);
    eos_storage_write_file(TH_HIST_FILE, buf, (size_t)n);
}

static void _write_history(const char *path, uint32_t pos)
{
    if (!path) return;
    _fm_hist_write(path, pos);
}

/* 解析历史中的展开记录行:"p1|p2|p3"(行尾最新),只取最新 TH_FM_EXP_MAX 个 */
static void _fm_exp_parse(const char *line)
{
    s_fm_exp_count = 0;
    if (!line || !line[0]) return;
    const char *tok = line;
    while (tok && *tok && s_fm_exp_count < TH_FM_EXP_MAX) {
        const char *sep = strchr(tok, '|');
        size_t len = sep ? (size_t)(sep - tok) : strlen(tok);
        if (len > 0 && len < EOS_FS_PATH_MAX &&
            strncmp(tok, TH_DIR, strlen(TH_DIR)) == 0) {
            memcpy(s_fm_exp[s_fm_exp_count], tok, len);
            s_fm_exp[s_fm_exp_count][len] = '\0';
            s_fm_exp_count++;
        }
        if (!sep) break;
        tok = sep + 1;
    }
}

/* 展开一个目录:已存在则移到末尾(最新);超过 TH_FM_EXP_MAX 个则丢弃最旧 */
static void _fm_exp_add(const char *path)
{
    if (!path || !path[0]) return;
    for (int i = 0; i < s_fm_exp_count; i++) {
        if (strcmp(s_fm_exp[i], path) == 0) {
            if (i != s_fm_exp_count - 1) {
                memmove(&s_fm_exp[i], &s_fm_exp[i + 1],
                        (size_t)(s_fm_exp_count - 1 - i) * sizeof(s_fm_exp[0]));
                s_fm_exp_count--;
                strncpy(s_fm_exp[s_fm_exp_count], path,
                        sizeof(s_fm_exp[0]) - 1);
                s_fm_exp[s_fm_exp_count][sizeof(s_fm_exp[0]) - 1] = '\0';
                s_fm_exp_count++;
            }
            _fm_hist_write(s_cur_path, s_cur_pos);
            return;
        }
    }
    if (s_fm_exp_count >= TH_FM_EXP_MAX) {
        memmove(&s_fm_exp[0], &s_fm_exp[1],
                (size_t)(s_fm_exp_count - 1) * sizeof(s_fm_exp[0]));
        s_fm_exp_count--;
    }
    strncpy(s_fm_exp[s_fm_exp_count], path, sizeof(s_fm_exp[0]) - 1);
    s_fm_exp[s_fm_exp_count][sizeof(s_fm_exp[0]) - 1] = '\0';
    s_fm_exp_count++;
    _fm_hist_write(s_cur_path, s_cur_pos);
}

/* 收起一个目录:历史中包含才删除,否则不处理 */
static void _fm_exp_remove(const char *path)
{
    if (!path || !path[0]) return;
    for (int i = 0; i < s_fm_exp_count; i++) {
        if (strcmp(s_fm_exp[i], path) == 0) {
            memmove(&s_fm_exp[i], &s_fm_exp[i + 1],
                    (size_t)(s_fm_exp_count - 1 - i) * sizeof(s_fm_exp[0]));
            s_fm_exp_count--;
            _fm_hist_write(s_cur_path, s_cur_pos);
            return;
        }
    }
}

static bool _open_path(const char *path)
{
    if (!path || !_is_text_ext(path)) return false;

    eos_file_t fp = eos_storage_file_open_read(path);
    if (fp == EOS_FILE_INVALID) {
        EOS_LOG_W("Texthub: open fail %s", path);
        _show_centered_msg("OPEN FAIL");
        return false;
    }

    uint32_t size = 0;
    if (eos_storage_file_size(fp, &size) != EOS_OK) {
        eos_storage_file_close(fp);
        _show_centered_msg("SIZE FAIL");
        return false;
    }
    if (size > TH_MAX_FILE_SIZE) {
        eos_storage_file_close(fp);
        _show_centered_msg("FILE TOO BIG");
        return false;
    }

    /* release previous file */
    _free_text();
    if (s_cur_path) { eos_free(s_cur_path); s_cur_path = NULL; }
    if (s_cur_dir)  { eos_free(s_cur_dir);  s_cur_dir  = NULL; }

    s_fp  = fp;
    s_size = size;

    if (size <= TH_READ_ONCE_MAX) {
        s_seg_mode = false;
        char *txt = (char *)eos_malloc(size + 1);
        if (!txt) {
            _free_text();
            _show_centered_msg("NO MEM");
            return false;
        }
        ssize_t rd = eos_storage_file_read(fp, txt, size);
        if (rd < 0) rd = 0;
        txt[rd] = '\0';
        s_text = txt;
    } else {
        s_seg_mode = true;
        if (!_seg_load(0)) {
            _free_text();
            _show_centered_msg("READ FAIL");
            return false;
        }
    }

    s_cur_path = eos_strdup(path);
    char dirbuf[EOS_FS_PATH_MAX];
    _dir_of(path, dirbuf, sizeof(dirbuf));
    s_cur_dir = eos_strdup(dirbuf);

    /* index / total within the same directory */
    int count = 0, idx = -1;
    char **names = _scan_text_names(s_cur_dir, &count, path, &idx);
    _free_names(names, count);
    s_cur_idx   = (idx >= 0) ? idx : 0;
    s_cur_total = count;

    /* render */
    lv_label_set_text(s_body, s_text);
    lv_obj_update_layout(s_card);
    lv_obj_scroll_to_y(s_card, 0, LV_ANIM_OFF);
    _update_bar();

    /* a fresh file always starts at the top */
    s_cur_pos = 0;
    _write_history(path, s_cur_pos);
    EOS_LOG_I("Texthub: opened %s (%u bytes%s)", path, size,
              s_seg_mode ? ", seg-mode" : "");
    return true;
}

/* [>] next file in the same directory */
static void _next_file(void)
{
    if (!s_cur_path || !s_cur_dir) return;

    int count = 0, idx = -1;
    char **names = _scan_text_names(s_cur_dir, &count, s_cur_path, &idx);
    if (!names || idx < 0 || idx >= count - 1) {
        _free_names(names, count);
        return;
    }
    char next_path[EOS_FS_PATH_MAX];
    snprintf(next_path, sizeof(next_path), "%s/%s", s_cur_dir, names[idx + 1]);
    _free_names(names, count);

    _open_path(next_path);
}

/* [<] previous file in the same directory */
static void _prev_file(void)
{
    if (!s_cur_path || !s_cur_dir) return;

    int count = 0, idx = -1;
    char **names = _scan_text_names(s_cur_dir, &count, s_cur_path, &idx);
    if (!names || idx <= 0) {
        _free_names(names, count);
        return;
    }
    char prev_path[EOS_FS_PATH_MAX];
    snprintf(prev_path, sizeof(prev_path), "%s/%s", s_cur_dir, names[idx - 1]);
    _free_names(names, count);

    _open_path(prev_path);
}

/* Trash can: delete the current file, then open the next one in the same
 * directory (or the first, or show an empty state). */
static void _trash_cb(lv_event_t *e)
{
    (void)e;
    if (!s_cur_path) return;
    EOS_LOG_I("Texthub: delete %s", s_cur_path);

    char dirbuf[EOS_FS_PATH_MAX];
    strncpy(dirbuf, s_cur_dir ? s_cur_dir : TH_DIR, sizeof(dirbuf) - 1);
    dirbuf[sizeof(dirbuf) - 1] = '\0';
    char cur[EOS_FS_PATH_MAX];
    strncpy(cur, s_cur_path, sizeof(cur) - 1);
    cur[sizeof(cur) - 1] = '\0';

    eos_storage_file_remove(s_cur_path);

    /* if the FM anchor points at the deleted file, drop it */
    if (s_fm_anchor[0] && strcmp(s_fm_anchor, cur) == 0) {
        s_fm_anchor[0] = '\0';
    }

    /* if history points at the deleted file, drop the record */
    if (eos_storage_is_file(TH_HIST_FILE)) {
        char *last = eos_storage_read_file(TH_HIST_FILE);
        if (last) {
            size_t cl = strlen(cur);
            if (strncmp(last, cur, cl) == 0 &&
                (last[cl] == '\0' || last[cl] == '\n')) {
                eos_storage_file_remove(TH_HIST_FILE);
            }
            eos_free(last);
        }
    }

    /* release current file */
    _free_text();
    eos_free(s_cur_path); s_cur_path = NULL;
    eos_free(s_cur_dir);  s_cur_dir  = NULL;
    s_cur_idx = s_cur_total = 0;
    s_cur_pos = 0;

    /* reopen the next remaining file, or the first, or empty state */
    int count = 0, idx = -1;
    char **names = _scan_text_names(dirbuf, &count, cur, &idx);
    int target = -1;
    if (names && count > 0) {
        target = (idx >= 0 && idx + 1 < count) ? idx + 1 : 0;
    }
    if (target >= 0) {
        char next_path[EOS_FS_PATH_MAX];
        snprintf(next_path, sizeof(next_path), "%s/%s", dirbuf, names[target]);
        _free_names(names, count);
        _open_path(next_path);
    } else {
        _free_names(names, count);
        _show_centered_msg("NO FILES\nTap FM to browse");
        lv_label_set_text(s_name, "Texthub");
        lv_label_set_text(s_bottom, "");
    }
}


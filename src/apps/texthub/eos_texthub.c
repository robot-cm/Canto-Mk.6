static bool _on_swipe_back(eos_activity_t *self, lv_dir_t dir)
{
    (void)self;
    (void)dir;
    if (s_fm_open) { _fm_close(); return true; }
    return false;
}

static void _on_enter(eos_activity_t *act)
{
    s_act = act;
    _build_ui(act);

    /* try history first */
    if (eos_storage_is_file(TH_HIST_FILE)) {
        char *last = eos_storage_read_file(TH_HIST_FILE);
        if (last) {
            uint32_t pos = 0;
            char *nl = strchr(last, '\n');
            if (nl) {
                /* format: "<path>\n<pos>\n<fm_anchor>\n" */
                *nl = '\0';
                const char *ps = nl + 1;
                char *pe = strchr(ps, '\n');
                if (pe) *pe = '\0';
                pos = (uint32_t)strtoul(ps, NULL, 10);
                if (pos > 10000) pos = 10000;
                /* line 3: FM anchor (last file opened from the FM) */
                if (pe && pe[1] != '\0') {
                    char *l3 = pe + 1;
                    char *nl3 = strchr(l3, '\n');
                    if (nl3) *nl3 = '\0';
                    size_t l3len = strlen(l3);
                    while (l3len > 0 && (l3[l3len - 1] == '\r' ||
                                         l3[l3len - 1] == ' ')) {
                        l3[--l3len] = '\0';
                    }
                    if (l3len > 0 &&
                        strncmp(l3, TH_DIR "/", strlen(TH_DIR) + 1) == 0 &&
                        eos_storage_is_file(l3)) {
                        strncpy(s_fm_anchor, l3, sizeof(s_fm_anchor) - 1);
                        s_fm_anchor[sizeof(s_fm_anchor) - 1] = '\0';
                    }
                    /* line 4: 最近展开的文件夹(最多 3 个,| 分隔,行尾最新) */
                    if (nl3 && nl3[1] != '\0') {
                        char *l4 = nl3 + 1;
                        char *nl4 = strchr(l4, '\n');
                        if (nl4) *nl4 = '\0';
                        size_t l4len = strlen(l4);
                        while (l4len > 0 && (l4[l4len - 1] == '\r' ||
                                             l4[l4len - 1] == ' ')) {
                            l4[--l4len] = '\0';
                        }
                        _fm_exp_parse(l4);
                    }
                }
            } else {
                /* legacy format: bare path only (position = top) */
                size_t len = strlen(last);
                while (len > 0 && (last[len - 1] == '\n' || last[len - 1] == '\r')) {
                    last[--len] = '\0';
                }
            }
            size_t len = strlen(last);
            if (len > 1 && strncmp(last, TH_DIR "/", strlen(TH_DIR) + 1) == 0) {
                if (eos_storage_is_file(last) && _open_path(last)) {
                    eos_free(last);
                    _restore_pos(pos);
                    return;
                }
            }
            eos_free(last);
        }
    }
    /* no valid record -> File Manager */
    EOS_LOG_I("Texthub: no valid history, open FM");
    if (s_cur_path) {
        _free_text();
        eos_free(s_cur_path); s_cur_path = NULL;
        eos_free(s_cur_dir);  s_cur_dir  = NULL;
        s_cur_idx = s_cur_total = 0;
        lv_label_set_text(s_name, "Texthub");
        lv_label_set_text(s_bottom, "");
    }
    _show_centered_msg("NO FILES\nTap FM to browse");
    _fm_open();
}

static void _on_destroy(eos_activity_t *act)
{
    (void)act;
    /* persist the reading position (view is still valid during on_destroy) */
    if (s_cur_path) {
        _update_cur_pos();
        _write_history(s_cur_path, s_cur_pos);
    }
    _fm_close();
    _free_text();
    if (s_cur_path) { eos_free(s_cur_path); s_cur_path = NULL; }
    if (s_cur_dir)  { eos_free(s_cur_dir);  s_cur_dir  = NULL; }
    s_cur_idx = s_cur_total = 0;
    s_cur_pos = 0;
}

static const eos_activity_lifecycle_t s_lifecycle = {
    .on_enter      = _on_enter,
    .on_destroy    = _on_destroy,
    .on_swipe_back = _on_swipe_back,
};

void eos_texthub_enter(void)
{
    EOS_LOG_I("Texthub: enter");
    eos_activity_t *act = eos_activity_create(&s_lifecycle);
    eos_activity_set_type(act, EOS_ACTIVITY_TYPE_APP);
    eos_activity_set_app_header_visible(act, false);
    eos_activity_set_title(act, "Texthub");
    eos_activity_enter(act);
}

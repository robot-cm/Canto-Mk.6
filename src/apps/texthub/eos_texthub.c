/* Show / hide the capsule and the side arrows while the text scrolls. */
static void _ui_controls(bool vis)
{
    lv_obj_t *objs[] = { s_prev_btn, s_next_btn, s_capsule };
    for (unsigned i = 0; i < sizeof(objs) / sizeof(objs[0]); i++) {
        if (!objs[i]) continue;
        if (vis) lv_obj_remove_flag(objs[i], LV_OBJ_FLAG_HIDDEN);
        else     lv_obj_add_flag(objs[i], LV_OBJ_FLAG_HIDDEN);
    }
}

static void _card_scroll_cb(lv_event_t *e)
{
    lv_event_code_t code = lv_event_get_code(e);
    if (code == LV_EVENT_SCROLL_BEGIN) {
        _ui_controls(false);            /* hide while reading / panning */
        return;
    }

    lv_obj_t *card = lv_event_get_target(e);
    if (s_restoring) return;            /* position restore in progress */

    _ui_controls(true);                 /* scroll stopped: bring back UI */

    /* keep reading position fresh (non-seg mode too) */
    _update_cur_pos();

    if (!s_seg_mode || s_fp == EOS_FILE_INVALID) return;

    int32_t sy = lv_obj_get_scroll_y(card);
    int32_t bottom = lv_obj_get_scroll_bottom(card);
    if (bottom <= 0) return;

    if (sy >= bottom - 6) {
        _seg_next();
    } else if (sy <= 0) {
        _seg_prev();
    }
}


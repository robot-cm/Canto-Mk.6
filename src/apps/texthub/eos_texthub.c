/**
 * @file eos_texthub.c
 * @brief Texthub - native C text reader (.txt/.md) for /sdcard/texthub/
 *
 * Replaces the old JS app (apps/texthub) which crashed with
 * JERRY_FATAL_OUT_OF_MEMORY because it synchronously enumerated every file
 * under /sdcard/texthub/ into the fixed 512KB JerryScript heap.
 *
 * C version design:
 *   - Lazy File Manager (FM) overlay: only the directory being expanded is
 *     read (eos_storage_dir_open); children are freed when collapsed or when
 *     the FM closes (memory stays small, no full-tree scan).
 *   - Chunked reading: files <= 128KB load in one shot; larger files are
 *     read segment-by-segment (16KB, newline-aligned) on scroll end.
 *   - History: /sdcard/history/texthub/latest.txt stores the last opened
 *     file path (line 1), reading position permille (line 2) and FM anchor
 *     (line 3: last file opened from the FM, restores the FM scroll
 *     position); the last file is auto-opened on entry (FM shown when
 *     absent).
 *   - UI (240x240 round, Album style): floating filename on top, prev/next
 *     arrows, bottom action capsule (delete + FM), bottom-left indicator.
 *     The capsule and arrows hide while the text scrolls and return when
 *     scrolling stops. English only; CJK shown via jbm_13's han_sans_13
 *     fallback.
 *
 * UI layout (all inside the round clipping region):
 *   System statusbar: y0..24 (owned by the framework)
 *   Floating filename: top-mid (0,24), w132, circular marquee
 *   Prev/next arrows: 30x56 at left/right mid
 *   Text card: x14 y60 w212 h132, rounded, drag-to-scroll
 *   Action capsule: 112x56 pill at bottom-mid (0,-12): delete + FM icons
 *   Bottom: bottom-left (8,-16), "idx/total | seg x"
 */


static uint32_t _fit_scale(uint32_t w, uint32_t h)
{
    uint32_t sx = (ALBUM_IMG_MAX * 256) / (w ? w : 1);
    uint32_t sy = (ALBUM_IMG_MAX * 256) / (h ? h : 1);
    uint32_t s = sx < sy ? sx : sy;
    if (s < 1) s = 1;
    if (s > 1024) s = 1024;
    return s;
}


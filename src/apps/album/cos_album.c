static int _cmp_path(const void *a, const void *b)
{
    const char *pa = _base((const char *)a);
    const char *pb = _base((const char *)b);
    return strcasecmp(pa, pb);
}

static int _load_dir_pics(const char *dir)
{
    if (s_paths) {
        cos_free(s_paths);
        s_paths = NULL;
    }
    s_count = 0;
    s_index = 0;

    if (!cos_storage_is_dir(dir)) return 0;

    s_paths = (char (*)[COS_FS_PATH_MAX])cos_malloc(ALBUM_MAX * COS_FS_PATH_MAX);
    if (!s_paths) return 0;

    cos_dir_t d = cos_storage_dir_open(dir);
    if (!d) return 0;

    char name[COS_FS_NAME_MAX];
    while (s_count < ALBUM_MAX &&
           cos_storage_dir_read(d, name, sizeof(name)) == COS_OK) {
        if (name[0] == '.') continue; /* skip dot entries */
        char full[COS_FS_PATH_MAX];
        size_t dl = strlen(dir), nl = strlen(name);
        if (dl + 1 + nl + 1 > sizeof(full)) continue; /* path too long */
        memcpy(full, dir, dl);
        full[dl] = '/';
        strcpy(full + dl + 1, name);
        if (cos_storage_is_file(full) && _is_image_ext(name)) {
            strncpy(s_paths[s_count], full, COS_FS_PATH_MAX - 1);
            s_paths[s_count][COS_FS_PATH_MAX - 1] = '\0';
            s_count++;
        }
    }
    cos_storage_dir_close(d);

    if (s_count > 1) {
        qsort(s_paths, s_count, COS_FS_PATH_MAX, _cmp_path);
    }
    return s_count;
}

static void _show_current(void);

/* Open a specific image: switch to its directory, locate it, show it. */
static bool _open_image_path(const char *path)
{
    if (!path || !path[0]) return false;

    /* derive directory from the path */
    char dir[COS_FS_PATH_MAX];
    const char *slash = strrchr(path, '/');
    if (!slash) return false;
    size_t dl = (size_t)(slash - path);
    if (dl == 0) return false;
    if (dl >= sizeof(dir)) return false;
    memcpy(dir, path, dl);
    dir[dl] = '\0';

    if (_load_dir_pics(dir) <= 0) {
        return false;
    }

    /* locate index of the opened path */
    s_restore_miss = false;
    bool found = false;
    for (int i = 0; i < s_count; i++) {
        if (strcmp(s_paths[i], path) == 0) {
            s_index = i;
            found = true;
            break;
        }
    }
    /* 目录图片数达到 ALBUM_MAX 上限被截断时,精确路径可能不在列表里:
     * 退回 basename 匹配(同目录下文件名唯一,安全) */
    if (!found) {
        const char *want = _base(path);
        for (int i = 0; i < s_count; i++) {
            if (strcasecmp(_base(s_paths[i]), want) == 0) {
                s_index = i;
                found = true;
                break;
            }
        }
    }
    /* 仍找不到:显示第一张,但不覆盖上次的 history 记录 */
    if (!found) {
        s_index = 0;
        s_restore_miss = true;
    }
    _show_current();
    return true;
}


/* JPEG decode (TJpgDec, streamed from SD)                            */
/* ------------------------------------------------------------------ */

static size_t _jd_in(JDEC *jd, uint8_t *buf, size_t nd)
{
    _dec_ctx_t *c = (_dec_ctx_t *)jd->device;
    if (!buf) { /* skip nd bytes */
        uint32_t pos = 0;
        if (cos_storage_file_tell(c->fp, &pos) != COS_OK) {
            COS_LOG_E("Album: skip tell FAIL");
            return 0;
        }
        if (cos_storage_file_seek(c->fp, pos + nd) != COS_OK) {
            COS_LOG_E("Album: skip seek FAIL pos=%u nd=%u", pos, (unsigned)nd);
            return 0;
        }
        return nd;
    }
    ssize_t rd = cos_storage_file_read(c->fp, buf, nd);
    return rd > 0 ? (size_t)rd : 0;
}

static int _jd_out(JDEC *jd, void *bitmap, JRECT *rect)
{
    _dec_ctx_t *c = (_dec_ctx_t *)jd->device;
    if (!c->out) return 0;

    uint16_t bw = rect->right - rect->left + 1;
    uint32_t stride = (uint32_t)c->out_w * 2;
    const uint8_t *src = (const uint8_t *)bitmap;
    uint8_t *dst = c->out + ((uint32_t)rect->top * c->out_w + rect->left) * 2;

    for (uint16_t y = rect->top; y <= rect->bottom; y++) {
        memcpy(dst, src, bw * 2);
        src += bw * 2;
        dst += stride;
    }
    return 1; /* continue */
}

static bool _decode_jpeg(const char *path, lv_image_dsc_t *dsc)
{
    cos_file_t fp = cos_storage_file_open_read(path);
    if (fp == COS_FILE_INVALID) {
        COS_LOG_E("Album: open FAIL %s", path);
        return false;
    }
    COS_LOG_I("Album: decode %s", path);

    /* TJpgDec working pool (huffman tables + MCU buffer), PSRAM to save IRAM */
    uint8_t *work = (uint8_t *)cos_malloc(ALBUM_WORK_SIZE);
    if (!work) {
        COS_LOG_E("Album: work malloc FAIL size=%u", (unsigned)ALBUM_WORK_SIZE);
        cos_storage_file_close(fp);
        return false;
    }

    _dec_ctx_t ctx;
    ctx.fp    = fp;
    ctx.out   = NULL;
    ctx.out_w = 0;

    JDEC jd;
    JRESULT rc = jd_prepare(&jd, _jd_in, work, ALBUM_WORK_SIZE, &ctx);
    if (rc != JDR_OK) {
        COS_LOG_E("Album: jd_prepare FAIL rc=%d", (int)rc);
        cos_free(work);
        cos_storage_file_close(fp);
        return false;
    }

    uint16_t w = jd.width, h = jd.height;
    /* TJpgDec scale = right shift count: 0=full, 1=1/2, 2=1/4, 3=1/8 (max) */
    uint8_t scale = 0;
    uint16_t ow = w, oh = h;
    while (scale < 3 && (ow > ALBUM_DECODE_MAX || oh > ALBUM_DECODE_MAX)) {
        scale++;
        ow >>= 1;
        oh >>= 1;
    }
    if (ow == 0 || oh == 0 || ow > ALBUM_DECODE_MAX || oh > ALBUM_DECODE_MAX) {
        COS_LOG_E("Album: jpeg %ux%u too large even at 1/8", w, h);
        cos_free(work);
        cos_storage_file_close(fp);
        return false; /* too large even at 1/8 */
    }

    uint32_t npix = (uint32_t)ow * oh * 2;
    uint8_t *pix = (uint8_t *)cos_malloc(npix);
    if (!pix) {
        COS_LOG_E("Album: pix malloc FAIL size=%u", (unsigned)npix);
        cos_free(work);
        cos_storage_file_close(fp);
        return false;
    }

    ctx.out   = pix;
    ctx.out_w = ow;

    COS_LOG_I("Album: jpeg %ux%u scale=%u -> %ux%u", w, h, scale, ow, oh);

    JRESULT drc = jd_decomp(&jd, _jd_out, scale);
    if (drc != JDR_OK) {
        COS_LOG_E("Album: jd_decomp FAIL rc=%d w=%u h=%u scale=%u", (int)drc, w, h, scale);
        cos_free(pix);
        cos_free(work);
        cos_storage_file_close(fp);
        return false;
    }

    cos_free(work);
    cos_storage_file_close(fp);

    memset(dsc, 0, sizeof(*dsc));
    dsc->header.magic  = LV_IMAGE_HEADER_MAGIC;
    dsc->header.cf     = LV_COLOR_FORMAT_RGB565;
    dsc->header.w      = ow;
    dsc->header.h      = oh;
    dsc->header.stride = ow * 2;
    dsc->data          = pix;
    dsc->data_size     = npix;
    return true;
}


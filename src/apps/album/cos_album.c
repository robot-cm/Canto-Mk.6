static void _fm_children_free(_fm_node_t *n)
{
    if (!n) return;
    if (n->children) {
        for (int i = 0; i < n->child_count; i++) {
            _fm_children_free(&n->children[i]);
        }
        cos_free(n->children);
        n->children = NULL;
    }
    n->child_count = 0;
    n->loaded = false;
    n->expanded = false;
}

static int _fm_cmp(const void *a, const void *b)
{
    const _fm_node_t *na = (const _fm_node_t *)a;
    const _fm_node_t *nb = (const _fm_node_t *)b;
    if (na->is_dir != nb->is_dir) return nb->is_dir - na->is_dir;
    return strcasecmp(na->name, nb->name);
}

/* Lazy load: read one directory into an array of children nodes. */
static bool _fm_node_load(_fm_node_t *n)
{
    if (n->loaded) return true;
    if (n->depth >= FM_DEPTH_MAX) { n->loaded = true; return false; }

    /* pass 1: count entries */
    cos_dir_t d = cos_storage_dir_open(n->path);
    if (!d) {
        /* 不置 loaded=true:打开失败可重试,否则目录会永久显示为空 */
        COS_LOG_W("Album: opendir FAIL %s (retryable)", n->path);
        return false;
    }
    int cnt = 0;
    char name[COS_FS_NAME_MAX];
    while (cos_storage_dir_read(d, name, sizeof(name)) == COS_OK) {
        if (name[0] == '\0' || name[0] == '.') continue;
        if (++cnt > FM_MAX_CHILD) { cnt = FM_MAX_CHILD; break; }
    }
    cos_storage_dir_close(d);
    COS_LOG_I("Album: dir %s raw=%d", n->path, cnt);

    if (cnt == 0) { n->loaded = true; return false; }

    _fm_node_t *arr = (_fm_node_t *)cos_malloc_zeroed((size_t)cnt * sizeof(_fm_node_t));
    if (!arr) { n->loaded = true; return false; }

    /* pass 2: fill, keeping only directories + images */
    d = cos_storage_dir_open(n->path);
    if (!d) { cos_free(arr); n->loaded = true; return false; }
    int i = 0;
    while (i < cnt && cos_storage_dir_read(d, name, sizeof(name)) == COS_OK) {
        if (name[0] == '\0' || name[0] == '.') continue;
        char full[COS_FS_PATH_MAX];
        size_t dl = strlen(n->path), nl = strlen(name);
        if (dl + 1 + nl + 1 > sizeof(full)) continue;
        memcpy(full, n->path, dl);
        full[dl] = '/';
        strcpy(full + dl + 1, name);

        bool is_dir = cos_storage_is_dir(full);
        if (!is_dir && !_is_image_ext(name)) continue; /* only dirs + images */

        _fm_node_t *c = &arr[i];
        strncpy(c->name, name, sizeof(c->name) - 1);
        c->name[sizeof(c->name) - 1] = '\0';
        strncpy(c->path, full, sizeof(c->path) - 1);
        c->path[sizeof(c->path) - 1] = '\0';
        c->is_dir = is_dir;
        c->depth  = n->depth + 1;
        i++;
        if (i >= FM_MAX_CHILD) break;
    }
    cos_storage_dir_close(d);

    n->children = arr;
    n->child_count = i;
    n->loaded = true;
    if (i > 1) {
        qsort(arr, (size_t)i, sizeof(_fm_node_t), _fm_cmp);
    }
    COS_LOG_I("Album: dir %s children=%d", n->path, i);
    return i > 0;
}

/* 先数可见行再按需扩容模型数组:固定容量会截断大目录,导致定位找不到目标行 */
static int _fm_count_items(_fm_node_t *n)
{
    if (!n) return 0;
    int c = 1;
    if (n->is_dir && n->expanded && n->children) {
        for (int i = 0; i < n->child_count; i++) {
            c += _fm_count_items(&n->children[i]);
        }
    }
    return c;
}

static bool _fm_items_reserve(int need)
{
    if (need <= s_fm_cap) return true;
    int cap = s_fm_cap > 0 ? s_fm_cap : 160;
    while (cap < need) cap *= 2;
    if (cap > FM_MAX_VISIBLE) cap = FM_MAX_VISIBLE;
    if (need > cap) return false;
    size_t bytes = (size_t)cap * sizeof(_fm_item_t);
    _fm_item_t *p = s_fm_items ? (_fm_item_t *)cos_realloc(s_fm_items, bytes)
                               : (_fm_item_t *)cos_malloc(bytes);
    if (!p) {
        COS_LOG_E("Album: items grow FAIL need=%d", need);
        return false;
    }
    s_fm_items = p;
    s_fm_cap   = cap;
    return true;
}

static void _fm_build_items(_fm_node_t *n, int depth, int *cnt)
{
    if (!n) return;
    s_fm_items[*cnt].node = n;
    s_fm_items[*cnt].depth = depth;
    (*cnt)++;

    /* only directories recurse (images are leaves: click opens them) */
    if (n->is_dir && n->expanded && n->children) {
        for (int i = 0; i < n->child_count; i++) {
            _fm_build_items(&n->children[i], depth + 1, cnt);
        }
    }
}

static void _fm_row_cb(lv_event_t *e); /* fwd decl */
static void _fm_arrow_cb(lv_event_t *e);
static void _fm_make_row(int i);
static void _fm_update_window(bool force);
static void _fm_list_scroll_cb(lv_event_t *e);

static void _fm_rebuild(void)
{
    if (!s_fm_open || !s_fm_list) {
        COS_LOG_W("Album: rebuild skip open=%d list=%p", s_fm_open, (void *)s_fm_list);
        return;
    }

    /* 保存滚动位置:clean 后内容高度归零,LVGL 会把 scroll 清零导致
     * 展开/收起后跳回列表顶部 */
    int32_t scroll_y = lv_obj_get_scroll_y(s_fm_list);

    if (!s_fm_root) {
        COS_LOG_E("Album: rebuild root NULL");
        return;
    }
    if (!s_fm_root->loaded) _fm_node_load(s_fm_root);

    int need = _fm_count_items(s_fm_root);
    if (!_fm_items_reserve(need)) return;

    int cnt = 0;
    _fm_build_items(s_fm_root, 0, &cnt);
    s_fm_item_count = cnt;

    /* 虚拟列表容器:高度 = 全部行高,行只在视口附近按需创建,避免一次
     * 创建上百行阻塞 UI 任务(真机会触发 task_wdt) */
    if (!s_fm_cont) {
        s_fm_cont = lv_obj_create(s_fm_list);
        lv_obj_remove_style_all(s_fm_cont);
        lv_obj_clear_flag(s_fm_cont, LV_OBJ_FLAG_SCROLLABLE);
        lv_obj_clear_flag(s_fm_cont, LV_OBJ_FLAG_CLICKABLE);
        lv_obj_set_pos(s_fm_cont, 0, 0);
        lv_obj_add_event_cb(s_fm_list, _fm_list_scroll_cb, LV_EVENT_SCROLL, NULL);
    }
    int list_w = lv_obj_get_width(s_fm_list);
    if (list_w <= 0) list_w = 196;
    lv_obj_set_size(s_fm_cont, list_w, cnt > 0 ? cnt * FM_ROW_H : 1);
    lv_obj_clean(s_fm_cont);
    s_fm_win_first = s_fm_win_last = -1;

    if (scroll_y > 0) lv_obj_scroll_to_y(s_fm_list, scroll_y, LV_ANIM_OFF);
    _fm_update_window(true);
}

/* 创建第 i 行(索引基于扁平模型 s_fm_items) */
static void _fm_make_row(int i)
{
    {
        _fm_node_t *node = s_fm_items[i].node;
        int depth = s_fm_items[i].depth;
        int list_w = lv_obj_get_width(s_fm_cont);
        if (list_w <= 0) list_w = 196;
        int name_w = list_w - 30 - 8; /* indent room + arrow */

        lv_obj_t *row = lv_button_create(s_fm_cont);
        lv_obj_remove_style_all(row);
        lv_obj_set_size(row, list_w, FM_ROW_H);
        /* rows must not be scroll targets or they swallow the drag gesture */
        lv_obj_clear_flag(row, LV_OBJ_FLAG_SCROLLABLE);
        lv_obj_set_style_bg_color(row, lv_color_hex(_UI_TEXT), 0);
        lv_obj_set_style_bg_opa(row, i % 2 ? 10 : 0, 0);   /* faint zebra */
        lv_obj_set_style_radius(row, 8, 0);
        lv_obj_set_style_border_width(row, 0, 0);
        lv_obj_set_style_pad_all(row, 0, 0);
        lv_obj_set_pos(row, 0, i * FM_ROW_H);

        char rowbuf[COS_FS_NAME_MAX + 4];
        if (node->is_dir) {
            snprintf(rowbuf, sizeof(rowbuf), "%s/", node->name);
        } else {
            snprintf(rowbuf, sizeof(rowbuf), "%s", node->name);
        }

        lv_obj_t *lbl = lv_label_create(row);
        /* 文件名可能含中文:必须走带 CJK 字形的字体档,不能用 lv_font_montserrat_*
         * (纯 ASCII,中文会渲染成下划线)。
         * 13px 档链路:jbm_13 → han_sans_13(GB2312 一级 3755 字)
         *            → han_sans_16(175 字) → han_sans_22(GB2312 全量 6749 字),
         * 即常用简体字全覆盖,仅二级字库外的生僻字(垚/玥/燊 等)会缺失。
         * 另:文件名本身能否带中文由 FATFS 决定(见 sdkconfig.defaults 的
         * CONFIG_FATFS_CODEPAGE_936 + API_ENCODING_UTF_8);若那两项缺失,
         * 中文名在 readdir 阶段就被替换成 '_' 并退化为 8.3 短名,与本处无关。 */
        cos_label_set_font_size(lbl, COS_FONT_SIZE_MICRO);
        lv_obj_set_style_text_color(lbl, node->is_dir ? lv_color_hex(_UI_ACCENT)
                                                      : lv_color_hex(_UI_TEXT), 0);
        lv_obj_set_style_text_opa(lbl, LV_OPA_COVER, 0);
        lv_obj_set_width(lbl, name_w);
        lv_obj_align(lbl, LV_ALIGN_LEFT_MID, 8 + depth * 12, 0);
        lv_label_set_long_mode(lbl, LV_LABEL_LONG_MODE_CLIP);
        lv_obj_set_style_text_align(lbl, LV_TEXT_ALIGN_LEFT, 0);
        lv_label_set_text(lbl, rowbuf);
        lv_obj_remove_flag(lbl, LV_OBJ_FLAG_CLICKABLE);
        lv_obj_remove_flag(lbl, LV_OBJ_FLAG_SCROLLABLE);

        {
            /* 箭头是唯一可点热区:文件夹点箭头展开/收起,文件点箭头直接打开
             * (点行本身不反应)。文件夹展开时显示下箭头,其余显示右箭头。 */
            lv_obj_t *arrbtn = lv_button_create(row);
            lv_obj_remove_style_all(arrbtn);
            lv_obj_set_size(arrbtn, 34, FM_ROW_H);
            lv_obj_align(arrbtn, LV_ALIGN_RIGHT_MID, -2, 0);
            lv_obj_clear_flag(arrbtn, LV_OBJ_FLAG_SCROLLABLE);
            lv_obj_set_style_bg_opa(arrbtn, 0, 0);
            lv_obj_set_style_bg_opa(arrbtn, 60, LV_STATE_PRESSED);
            lv_obj_set_style_radius(arrbtn, 6, 0);
            lv_obj_add_event_cb(arrbtn, _fm_arrow_cb, LV_EVENT_CLICKED, node);
            lv_obj_t *arr = lv_label_create(arrbtn);
            lv_obj_set_style_text_font(arr, &COS_FONT_ICON, 0);
            lv_obj_set_style_text_color(arr, lv_color_hex(_UI_DIM), 0);
            lv_label_set_text(arr, node->expanded ? RI_ARROW_DOWN_S_LINE
                                                  : RI_ARROW_RIGHT_S_LINE);
            lv_obj_center(arr);
        }

        lv_obj_add_event_cb(row, _fm_row_cb, LV_EVENT_CLICKED, node);
    }
}

/* 只渲染视口附近的行(虚拟列表),窗口移动才重建 */
static void _fm_update_window(bool force)
{
    if (!s_fm_list || !s_fm_cont || s_fm_item_count <= 0) return;

    int32_t sy = lv_obj_get_scroll_y(s_fm_list);
    int32_t h  = lv_obj_get_height(s_fm_list);
    if (h <= 0) h = 158;

    int first = (int)(sy / FM_ROW_H) - FM_OVERSCAN;
    if (first < 0) first = 0;
    int last  = (int)((sy + h) / FM_ROW_H) + FM_OVERSCAN;
    if (last > s_fm_item_count - 1) last = s_fm_item_count - 1;
    if (!force && first == s_fm_win_first && last == s_fm_win_last) return;

    s_fm_win_first = first;
    s_fm_win_last  = last;
    lv_obj_clean(s_fm_cont);
    for (int i = first; i <= last; i++) _fm_make_row(i);
}

static void _fm_list_scroll_cb(lv_event_t *e)
{
    (void)e;
    _fm_update_window(false);
}

static void _fm_close(void)
{
    if (!s_fm_open) return;
    s_fm_open = false;

    if (s_fm_items) { cos_free(s_fm_items); s_fm_items = NULL; }
    s_fm_item_count = 0;
    s_fm_cap = 0;
    s_fm_cont = NULL;                    /* deleted with the list */
    s_fm_win_first = s_fm_win_last = -1;
    if (s_fm_root) {
        _fm_children_free(s_fm_root);
        cos_free(s_fm_root);   /* root itself is a single malloc'd node */
        s_fm_root = NULL;
    }

    if (s_fm_mask) { lv_obj_delete(s_fm_mask); s_fm_mask = NULL; }
    s_fm_panel = NULL;
    s_fm_list  = NULL;
    s_fm_title = NULL;
    s_fm_pos_btn = NULL;
    s_fm_pos_img = NULL;
}

/* 依次展开一个目录路径(含其父链,同步 IO 逐个展开)。目录已不存在时返回 false。 */
static bool _fm_expand_path(const char *path)
{
    if (!path || !path[0] || !s_fm_root) return false;
    if (strncmp(path, ALBUM_DIR, strlen(ALBUM_DIR)) != 0) return false;

    _fm_node_t *cur = s_fm_root;
    const char *p = path + strlen(ALBUM_DIR);
    char seg[COS_FS_NAME_MAX];

    while (*p) {
        while (*p == '/') p++;
        if (!*p) break;
        size_t n = 0;
        while (*p && *p != '/' && n < sizeof(seg) - 1) seg[n++] = *p++;
        seg[n] = '\0';

        if (!cur->loaded) _fm_node_load(cur);
        cur->expanded = true;            /* 展开父目录才能继续向下找 */

        _fm_node_t *match = NULL;
        for (int i = 0; i < cur->child_count; i++) {
            if (cur->children[i].is_dir &&
                strcmp(cur->children[i].name, seg) == 0) {
                match = &cur->children[i];
                break;
            }
        }
        if (!match) return false;
        cur = match;
    }
    if (!cur->loaded) _fm_node_load(cur);
    cur->expanded = true;
    return true;
}

/* FM 打开时,依次展开历史记录的文件夹;目录已消失的记录移除 */
static void _fm_restore_expanded(void)
{
    if (!s_fm_root) return;
    for (int i = 0; i < s_fm_exp_count; ) {
        if (_fm_expand_path(s_fm_exp[i])) {
            i++;
        } else {
            _fm_exp_remove(s_fm_exp[i]);   /* 目录没了,清掉记录 */
        }
    }
}

/* 依次展开 target 路径的父目录链,并把视口滚到该图片所在行。
 * 返回 true 表示文件行已在树中找到并完成滚动。路径不存在时返回 false。 */
static bool _fm_reveal(const char *target)
{
    if (!s_fm_root || !target || !target[0]) return false;
    if (strncmp(target, ALBUM_DIR, strlen(ALBUM_DIR)) != 0) return false;
    if (!_is_image_ext(_base(target))) return false;

    _fm_node_t *cur = s_fm_root;
    const char *p = target + strlen(ALBUM_DIR);
    char seg[COS_FS_NAME_MAX];
    bool changed = false;

    while (*p) {
        while (*p == '/') p++;          /* skip slashes */
        if (!*p) break;
        size_t n = 0;
        while (*p && *p != '/' && n < sizeof(seg) - 1) seg[n++] = *p++;
        seg[n] = '\0';
        if (!*p) break;                  /* last segment = the image file */

        if (!cur->loaded) _fm_node_load(cur);
        _fm_node_t *match = NULL;
        for (int i = 0; i < cur->child_count; i++) {
            if (cur->children[i].is_dir &&
                strcmp(cur->children[i].name, seg) == 0) {
                match = &cur->children[i];
                break;
            }
        }
        if (!match) break;               /* dir gone: keep what we expanded */
        match->expanded = true;
        changed = true;
        cur = match;
    }

    /* 循环结束时 cur 停在目标图片的父目录:它可能已 expanded 但 children 尚未
     * 加载,必须补一次加载,否则目标图片进不了扁平列表、定位会失败 */
    if (cur->is_dir && !cur->loaded) {
        _fm_node_load(cur);
        changed = true;
    }

    if (changed) _fm_rebuild();

    /* scroll so the image row is visible (vertically centred when possible) */
    for (int i = 0; i < s_fm_item_count; i++) {
        if (s_fm_items[i].node &&
            strcmp(s_fm_items[i].node->path, target) == 0) {
            int32_t y = i * FM_ROW_H - (158 - FM_ROW_H) / 2;
            if (y < 0) y = 0;
            lv_obj_scroll_to_y(s_fm_list, y, LV_ANIM_OFF);
            _fm_update_window(true);     /* render the rows now in view */
            return true;
        }
    }
    return false;
}

/* FM 打开时自动恢复滚动位置(锚点 = 上次从 FM 打开的图片) */
static void _fm_restore_position(void)
{
    _fm_reveal(s_fm_anchor);
}

/* FM 悬浮定位:把文件树滚到当前浏览的图片所在行 */
static void _fm_pos_cb(lv_event_t *e)
{
    (void)e;
    if (s_count <= 0) return;            /* nothing is being viewed */
    _fm_reveal(s_paths[s_index]);
}

/* 点行右侧箭头:文件夹展开/收起,文件直接打开(不冒泡到行,点行本身不响应) */
static void _fm_arrow_cb(lv_event_t *e)
{
    _fm_node_t *node = (_fm_node_t *)lv_event_get_user_data(e);
    if (!node) return;
    lv_event_stop_bubbling(e);   /* 箭头热区消费点击,行不响应 */
    if (node->is_dir) {
        if (node->expanded) {
            node->expanded = false;
            _fm_children_free(node);
            _fm_exp_remove(node->path);   /* 收起:历史中含则删,不含不处理 */
        } else {
            if (!node->loaded) _fm_node_load(node);
            node->expanded = true;
            _fm_exp_add(node->path);      /* 展开:记录到历史,只留最新 3 个 */
        }
        _fm_rebuild();
    } else {
        /* 文件:点箭头单击直接打开,记住 anchor 下次 FM 打开滚动到它 */
        char path[COS_FS_PATH_MAX];
        strncpy(path, node->path, sizeof(path) - 1);
        path[sizeof(path) - 1] = '\0';
        _write_fm_anchor(path);
        _fm_close();
        _open_image_path(path);
    }
}


static const char *_base(const char *path)
{
    const char *s = strrchr(path, '/');
    return s ? s + 1 : path;
}

static bool _is_image_ext(const char *name)
{
    const char *dot = strrchr(name, '.');
    if (!dot || dot[1] == '\0') return false;
    const char *e = dot + 1;
    return (strcasecmp(e, "jpg") == 0) || (strcasecmp(e, "jpeg") == 0) ||
           (strcasecmp(e, "png") == 0);
}

static bool _is_jpeg_ext(const char *name)
{
    const char *dot = strrchr(name, '.');
    if (!dot || dot[1] == '\0') return false;
    const char *e = dot + 1;
    return (strcasecmp(e, "jpg") == 0) || (strcasecmp(e, "jpeg") == 0);
}

/* Read PNG width/height from IHDR without decoding the whole file. */
static bool _png_dim(const char *path, uint32_t *w, uint32_t *h)
{
    eos_file_t fp = eos_storage_file_open_read(path);
    if (fp == EOS_FILE_INVALID) return false;

    uint8_t buf[24];
    if (eos_storage_file_read(fp, buf, sizeof(buf)) != (ssize_t)sizeof(buf)) {
        eos_storage_file_close(fp);
        return false;
    }
    eos_storage_file_close(fp);

    if (buf[0] != 0x89 || buf[1] != 'P' || buf[2] != 'N' || buf[3] != 'G') return false;

    *w = ((uint32_t)buf[16] << 24) | ((uint32_t)buf[17] << 16) |
         ((uint32_t)buf[18] << 8) | (uint32_t)buf[19];
    *h = ((uint32_t)buf[20] << 24) | ((uint32_t)buf[21] << 16) |
         ((uint32_t)buf[22] << 8) | (uint32_t)buf[23];
    return (*w > 0 && *h > 0);
}

/* ------------------------------------------------------------------ */
/* History: line 1 = last viewed image (resumed on enter, like TextHub);
 * line 2 = FM anchor (last image opened from the file manager, used to
 * restore the FM scroll position when the FM opens).                 */
/* ------------------------------------------------------------------ */

static char s_hist_img[EOS_FS_PATH_MAX];
static char s_fm_anchor[EOS_FS_PATH_MAX];

/* FM 展开记录:上次 FM 打开时展开过的目录(最多 FM_EXP_MAX 个,行尾最新) */
static char s_fm_exp[FM_EXP_MAX][EOS_FS_PATH_MAX];
static int  s_fm_exp_count;

static void _history_flush(void)
{
    char buf[EOS_FS_PATH_MAX * 6 + 16];
    int n = snprintf(buf, sizeof(buf), "%s\n%s\n", s_hist_img, s_fm_anchor);
    /* line 3: 最近展开的文件夹(最多 3 个,| 分隔,行尾最新) */
    for (int i = 0; i < s_fm_exp_count && n > 0 && n < (int)sizeof(buf); i++) {
        n += snprintf(buf + n, sizeof(buf) - (size_t)n, "%s%s",
                      i ? "|" : "", s_fm_exp[i]);
    }
    if (n < 0) n = 0;
    if ((size_t)n >= sizeof(buf)) n = (int)sizeof(buf) - 1;
    snprintf(buf + n, sizeof(buf) - (size_t)n, "\n");
    eos_storage_mkdir_recursive(ALBUM_HIST_DIR);
    eos_storage_write_file(ALBUM_HIST_FILE, buf, strlen(buf));
}

static void _write_history(const char *path)
{
    if (!path || !path[0]) return;
    strncpy(s_hist_img, path, sizeof(s_hist_img) - 1);
    s_hist_img[sizeof(s_hist_img) - 1] = '\0';
    _history_flush();
}

static void _write_fm_anchor(const char *path)
{
    if (!path || !path[0]) return;
    strncpy(s_fm_anchor, path, sizeof(s_fm_anchor) - 1);
    s_fm_anchor[sizeof(s_fm_anchor) - 1] = '\0';
    _history_flush();
}

/* 解析历史中的展开记录行:"p1|p2|p3"(行尾最新),只取最新 FM_EXP_MAX 个 */
static void _fm_exp_parse(const char *line)
{
    s_fm_exp_count = 0;
    if (!line || !line[0]) return;
    const char *tok = line;
    while (tok && *tok && s_fm_exp_count < FM_EXP_MAX) {
        const char *sep = strchr(tok, '|');
        size_t len = sep ? (size_t)(sep - tok) : strlen(tok);
        if (len > 0 && len < EOS_FS_PATH_MAX &&
            strncmp(tok, ALBUM_DIR, strlen(ALBUM_DIR)) == 0) {
            memcpy(s_fm_exp[s_fm_exp_count], tok, len);
            s_fm_exp[s_fm_exp_count][len] = '\0';
            s_fm_exp_count++;
        }
        if (!sep) break;
        tok = sep + 1;
    }
}

/* 展开一个目录:已存在则移到末尾(最新);超过 FM_EXP_MAX 个则丢弃最旧 */
static void _fm_exp_add(const char *path)
{
    if (!path || !path[0]) return;
    for (int i = 0; i < s_fm_exp_count; i++) {
        if (strcmp(s_fm_exp[i], path) == 0) {
            if (i != s_fm_exp_count - 1) {
                memmove(&s_fm_exp[i], &s_fm_exp[i + 1],
                        (size_t)(s_fm_exp_count - 1 - i) * sizeof(s_fm_exp[0]));
                s_fm_exp_count--;
                strncpy(s_fm_exp[s_fm_exp_count], path,
                        sizeof(s_fm_exp[0]) - 1);
                s_fm_exp[s_fm_exp_count][sizeof(s_fm_exp[0]) - 1] = '\0';
                s_fm_exp_count++;
            }
            _history_flush();
            return;
        }
    }
    if (s_fm_exp_count >= FM_EXP_MAX) {
        memmove(&s_fm_exp[0], &s_fm_exp[1],
                (size_t)(s_fm_exp_count - 1) * sizeof(s_fm_exp[0]));
        s_fm_exp_count--;
    }
    strncpy(s_fm_exp[s_fm_exp_count], path, sizeof(s_fm_exp[0]) - 1);
    s_fm_exp[s_fm_exp_count][sizeof(s_fm_exp[0]) - 1] = '\0';
    s_fm_exp_count++;
    _history_flush();
}

/* 收起一个目录:历史中包含才删除,否则不处理 */
static void _fm_exp_remove(const char *path)
{
    if (!path || !path[0]) return;
    for (int i = 0; i < s_fm_exp_count; i++) {
        if (strcmp(s_fm_exp[i], path) == 0) {
            memmove(&s_fm_exp[i], &s_fm_exp[i + 1],
                    (size_t)(s_fm_exp_count - 1 - i) * sizeof(s_fm_exp[0]));
            s_fm_exp_count--;
            _history_flush();
            return;
        }
    }
}

/* Trim trailing CR / spaces in place. Returns the trimmed length. */
static size_t _trim_line(char *s)
{
    size_t len = strlen(s);
    while (len > 0 && (s[len - 1] == '\r' || s[len - 1] == ' ')) {
        s[--len] = '\0';
    }
    return len;
}

/* Validate a history line as an existing image path under ALBUM_DIR. */
static bool _hist_line_valid(const char *s)
{
    return s && s[0] &&
           strncmp(s, ALBUM_DIR, strlen(ALBUM_DIR)) == 0 &&
           eos_storage_is_file(s);
}

static bool _read_history(char *out, size_t out_size)
{
    if (!out || out_size == 0) return false;
    out[0] = '\0';

    if (!eos_storage_is_file(ALBUM_HIST_FILE)) return false;

    char *content = eos_storage_read_file(ALBUM_HIST_FILE);
    if (!content) return false;

    /* line 1: last viewed image */
    char *nl = strchr(content, '\n');
    if (nl) *nl = '\0';
    _trim_line(content);
    bool valid = (strlen(content) > 0 && strlen(content) < out_size &&
                  _hist_line_valid(content));
    if (valid) {
        strncpy(out, content, out_size - 1);
        out[out_size - 1] = '\0';
    }

    /* line 2: FM anchor (absent on old single-line history files) */
    if (nl && nl[1] != '\0') {
        char *l2 = nl + 1;
        char *nl2 = strchr(l2, '\n');
        if (nl2) *nl2 = '\0';
        _trim_line(l2);
        if (_hist_line_valid(l2)) {
            strncpy(s_fm_anchor, l2, sizeof(s_fm_anchor) - 1);
            s_fm_anchor[sizeof(s_fm_anchor) - 1] = '\0';
        }
        /* line 3: 最近展开的文件夹(最多 3 个,| 分隔,行尾最新) */
        if (nl2 && nl2[1] != '\0') {
            char *l3 = nl2 + 1;
            char *nl3 = strchr(l3, '\n');
            if (nl3) *nl3 = '\0';
            _trim_line(l3);
            _fm_exp_parse(l3);
        }
    }
    eos_free(content);
    return valid;
}


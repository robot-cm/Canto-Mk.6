static uint32_t _fit_scale(uint32_t w, uint32_t h)
{
    uint32_t sx = (ALBUM_IMG_MAX * 256) / (w ? w : 1);
    uint32_t sy = (ALBUM_IMG_MAX * 256) / (h ? h : 1);
    uint32_t s = sx < sy ? sx : sy;
    if (s < 1) s = 1;
    if (s > 1024) s = 1024;
    return s;
}

/* Fit the thumbnail image into the display box, centered. The 1:1 browse
 * mode (tiles) handles magnification, so no zoom/pan here. */
static void _apply_view(void)
{
    if (!s_img || s_img_w <= 0 || s_img_h <= 0) return;
    lv_image_set_scale(s_img, _fit_scale(s_img_w, s_img_h));
    lv_obj_center(s_img);
}

static void _free_pixels(void)
{
    if (s_pixels) {
        eos_free(s_pixels);
        s_pixels = NULL;
    }
}


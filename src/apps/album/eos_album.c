/* Assets travel WITH each image, in hidden folders next to it, so a whole
 * package (one scripts/album_optimize.py run) is a single folder you can
 * drop anywhere under /sdcard/album/:
 *   <img dir>/.thumb/<base>.bin           : RGB565 LVGL bin, fitted <=240px
 *   <img dir>/.tiles/<base>/meta.txt      : "orig_w orig_h tile cols rows"
 *   <img dir>/.tiles/<base>/tile_<c>_<r>.bin
 * The file manager hides dot-directories, so these never show up. */

/* "/a/b/photo.jpg" -> dir="/a/b", base="photo" */
static void _dir_base(const char *img, char *dir, size_t dsz, char *base, size_t bsz)
{
    const char *slash = strrchr(img, '/');
    size_t dl = slash ? (size_t)(slash - img) : 0;
    if (dl >= dsz) dl = dsz - 1;
    memcpy(dir, img, dl);
    dir[dl] = '\0';
    const char *bn = slash ? slash + 1 : img;
    snprintf(base, bsz, "%s", bn);
    char *dot = strrchr(base, '.');
    if (dot) *dot = '\0'; /* strip extension only */
}

static void _thumb_path(const char *img, char *out, size_t sz)
{
    char dir[EOS_FS_PATH_MAX], base[EOS_FS_PATH_MAX];
    _dir_base(img, dir, sizeof(dir), base, sizeof(base));
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wformat-truncation"
    /* gcc over-estimates `base` length; ALBUM_PATH_BUF is sized for the real
     * (dir + .thumb/ + base + .bin) upper bound. */
    snprintf(out, sz, "%s/.thumb/%s.bin", dir, base);
#pragma GCC diagnostic pop
}

static void _tiles_dir(const char *img, char *out, size_t sz)
{
    char dir[EOS_FS_PATH_MAX], base[EOS_FS_PATH_MAX];
    _dir_base(img, dir, sizeof(dir), base, sizeof(base));
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wformat-truncation"
    snprintf(out, sz, "%s/.tiles/%s", dir, base);
#pragma GCC diagnostic pop
}

/* safe path scratch buffer: longest album path (EOS_FS_PATH_MAX) + mirror
 * prefix (/sdcard/album_thumbnail or /sdcard/album_tiles, +7) + suffix
 * (/tile_<c>_<r>.bin or /meta.txt) — keep generous so the (conservative)
 * -Wformat-truncation analysis stays quiet. */
#define ALBUM_PATH_BUF (EOS_FS_PATH_MAX + 64)

/* Read an LVGL bin file (12B header + pixels) into a fresh PSRAM buffer.
 * On success fills `dsc` (data points into the buffer) and returns the
 * buffer base in *alloc — free it with eos_free(). */
static bool _load_bin(const char *path, lv_image_dsc_t *dsc, uint8_t **alloc,
                      uint32_t *npix_out)
{
    eos_file_t fp = eos_storage_file_open_read(path);
    if (fp == EOS_FILE_INVALID) return false;

    uint8_t hdr[12]; /* magic|cf|flags(2)|w(2)|h(2)|stride(2)|reserved(2) */
    if (eos_storage_file_read(fp, hdr, sizeof(hdr)) != (ssize_t)sizeof(hdr)) {
        eos_storage_file_close(fp);
        return false;
    }
    if (hdr[0] != ALBUM_BIN_MAGIC || hdr[1] != ALBUM_BIN_CF) {
        eos_storage_file_close(fp);
        return false;
    }
    uint16_t w = (uint16_t)(hdr[4] | (hdr[5] << 8));
    uint16_t h = (uint16_t)(hdr[6] | (hdr[7] << 8));
    if (w == 0 || h == 0 || w > 2048 || h > 2048) {
        eos_storage_file_close(fp);
        return false;
    }
    uint32_t npix = (uint32_t)w * h * 2;
    uint8_t *buf = (uint8_t *)eos_malloc(12 + npix);
    if (!buf) {
        eos_storage_file_close(fp);
        return false;
    }
    memcpy(buf, hdr, sizeof(hdr));
    if (eos_storage_file_read(fp, buf + sizeof(hdr), npix) != (ssize_t)npix) {
        eos_free(buf);
        eos_storage_file_close(fp);
        return false;
    }
    eos_storage_file_close(fp);

    memset(dsc, 0, sizeof(*dsc));
    dsc->header.magic  = LV_IMAGE_HEADER_MAGIC;
    dsc->header.cf     = LV_COLOR_FORMAT_RGB565;
    dsc->header.w      = w;
    dsc->header.h      = h;
    dsc->header.stride = w * 2;
    dsc->data          = buf + sizeof(hdr);
    dsc->data_size     = npix;
    *alloc = buf;
    if (npix_out) *npix_out = npix;
    return true;
}

/* Thumbnail state: try the pre-encoded RGB565 bin first (zero decode,
 * ~112 KB buffer vs ~1.1 MB JPEG). Falls back to JPEG/PNG decode by caller. */
static bool _show_thumb(const char *path)
{
    char tp[ALBUM_PATH_BUF];
    _thumb_path(path, tp, sizeof(tp));
    uint8_t *buf = NULL;
    if (!_load_bin(tp, &s_dsc, &buf, NULL)) return false;
    eos_free(s_pixels);
    s_pixels = buf;                    /* keep alive until next show */
    s_img_w = s_dsc.header.w;
    s_img_h = s_dsc.header.h;
    lv_image_set_src(s_img, &s_dsc);
    lv_image_set_pivot(s_img, s_dsc.header.w / 2, s_dsc.header.h / 2);
    return true;
}


/* Remove the pre-encoded assets that travel with `img` (the thumbnail bin
 * and the whole 1:1 tile grid folder) so they never linger after delete. */
static void _delete_assets(const char *img)
{
    if (!img || !img[0]) return;
    char p[ALBUM_PATH_BUF];

    _thumb_path(img, p, sizeof(p));       /* <dir>/.thumb/<base>.bin */
    if (eos_storage_is_file(p)) eos_storage_file_remove(p);

    _tiles_dir(img, p, sizeof(p));        /* <dir>/.tiles/<base>/ */
    eos_dir_t d = eos_storage_dir_open(p);
    if (!d) return;
    char name[EOS_FS_NAME_MAX];
    while (eos_storage_dir_read(d, name, sizeof(name)) == EOS_OK) {
        if (name[0] == '\0' || name[0] == '.') continue;
        char full[ALBUM_PATH_BUF];
        snprintf(full, sizeof(full), "%s/%s", p, name);
        if (eos_storage_is_file(full)) eos_storage_file_remove(full);
    }
    eos_storage_dir_close(d);
}

static void _trash_cb(lv_event_t *e)
{
    (void)e;
    if (s_count <= 0) return;

    const char *path = s_paths[s_index];
    EOS_LOG_I("Album: delete %s", path);
    eos_storage_file_remove(path);
    _delete_assets(path);   /* also drop .thumb bin + .tiles grid */

    for (int i = s_index; i < s_count - 1; i++) {
        strcpy(s_paths[i], s_paths[i + 1]);
    }
    s_count--;
    if (s_count <= 0) {
        s_index = 0;
        _show_empty();
        return;
    }
    if (s_index >= s_count) s_index = s_count - 1;
    _show_current();
}

/* image touch gestures (single-point touch hardware):
 *  - double-tap (two press+release, small moves, < 300 ms apart)
 *                                        -> enter/exit 1:1 tile browse
 *  - drag (move while pressed, in 1:1)   -> pan the viewport
 * Only one touch point exists (CHSC6X), so no pinch.
 * A single tap never switches modes; only a double tap toggles, so a
 * swipe can never be mistaken for a zoom-out trigger. */
#define ALBUM_DOUBLE_TAP_MS 300
static int      s_press_x = 0, s_press_y = 0;  /* press origin (drag) */
static int      s_last_x  = 0, s_last_y  = 0;  /* last PRESSING sample */
static bool     s_dragging = false;
static uint32_t s_last_tap_t = 0;              /* tick of previous tap */

static void _img_event_cb(lv_event_t *e)
{
    lv_event_code_t code = lv_event_get_code(e);
    lv_indev_t *indev = lv_indev_active();
    if (!indev) return;
    lv_point_t p;
    lv_indev_get_point(indev, &p);

    if (code == LV_EVENT_PRESSED) {
        s_press_x = p.x;
        s_press_y = p.y;
        s_last_x  = p.x;
        s_last_y  = p.y;
        s_dragging = false;
    }
    else if (code == LV_EVENT_PRESSING) {
        /* per-event delta pans the viewport; TOTAL travel from the press
         * origin decides tap-vs-drag.  The old code compared only the last
         * per-event delta, so slow/fast swipes could stay under the 8 px
         * threshold forever and RELEASED then mistook a drag for a tap,
         * kicking the user back to the thumbnail. */
        int dx = p.x - s_last_x;
        int dy = p.y - s_last_y;
        s_last_x = p.x;
        s_last_y = p.y;
        if (!s_dragging) {
            int adx = p.x - s_press_x;
            int ady = p.y - s_press_y;
            if ((int)lv_sqrt32((uint32_t)(adx * adx + ady * ady)) > 8) {
                s_dragging = true;
            }
        }
        if (s_dragging && s_tile_mode && s_ts > 0) {
            /* content follows finger: viewport moves opposite */
            s_view_x -= dx;
            s_view_y -= dy;
            int mx = s_orig_w - ALBUM_VIEW;
            int my = s_orig_h - ALBUM_VIEW;
            if (mx < 0) mx = 0;
            if (my < 0) my = 0;
            if (s_view_x < 0) s_view_x = 0;
            if (s_view_x > mx) s_view_x = mx;
            if (s_view_y < 0) s_view_y = 0;
            if (s_view_y > my) s_view_y = my;
            _tile_refresh();
        }
    }
    else if (code == LV_EVENT_RELEASED) {
        if (!s_dragging && s_count > 0) {
            uint32_t now = lv_tick_get();
            if (s_last_tap_t && (now - s_last_tap_t) <= ALBUM_DOUBLE_TAP_MS) {
                /* second tap in the window -> toggle 1:1 browse */
                s_last_tap_t = 0;                /* consume the double tap */
                if (s_tile_mode) _tile_exit();
                else _tile_enter(p.x, p.y);
            } else {
                s_last_tap_t = now;              /* arm: wait for 2nd tap */
            }
        } else {
            s_last_tap_t = 0;                    /* a drag cancels tap */
        }
        s_dragging = false;
    }
}


static _tile_t *_tile_find(int c, int r)
{
    for (int i = 0; i < ALBUM_TILE_MAX; i++) {
        if (s_tiles[i].used && s_tiles[i].c == c && s_tiles[i].r == r)
            return &s_tiles[i];
    }
    return NULL;
}

static void _tile_unload(_tile_t *t)
{
    if (!t->used) return;
    if (t->img) {
        lv_obj_delete(t->img);
        t->img = NULL;
    }
    if (t->pixels) {
        eos_free(t->pixels);           /* give PSRAM back immediately */
        t->pixels = NULL;
    }
    t->used = false;
}

static void _tile_load(int c, int r)
{
    char dir[ALBUM_PATH_BUF], path[ALBUM_PATH_BUF];
    _tiles_dir(s_paths[s_index], dir, sizeof(dir));
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wformat-truncation"
    snprintf(path, sizeof(path), "%s/tile_%d_%d.bin", dir, c, r);
#pragma GCC diagnostic pop

    lv_image_dsc_t dsc;                /* local: copied into the slot below */
    uint8_t *buf = NULL;
    if (!_load_bin(path, &dsc, &buf, NULL)) {
        EOS_LOG_W("Album: tile %d,%d load FAIL", c, r);
        return;
    }
    _tile_t *t = NULL;
    for (int i = 0; i < ALBUM_TILE_MAX; i++) {
        if (!s_tiles[i].used) { t = &s_tiles[i]; break; }
    }
    if (!t) {                          /* no slot: drop, memory stays bounded */
        eos_free(buf);
        EOS_LOG_W("Album: tile slot full (%d,%d)", c, r);
        return;
    }
    t->c = c;
    t->r = r;
    t->w = (uint8_t)dsc.header.w;
    t->h = (uint8_t)dsc.header.h;
    t->pixels = buf;
    t->dsc = dsc;                      /* data points into buf+12 */
    t->used = true;
    t->img = lv_image_create(s_canvas);
    lv_image_set_src(t->img, &t->dsc);
    lv_obj_set_pos(t->img, c * s_ts - s_view_x, r * s_ts - s_view_y);
}

/* Load the tiles that cover the viewport (+1-tile margin) and drop the
 * rest. Called after every viewport move; keeps the working set small. */
static void _tile_refresh(void)
{
    if (!s_tile_mode || !s_canvas || s_ts <= 0) return;

    int c0 = s_view_x / s_ts;
    int c1 = (s_view_x + ALBUM_VIEW - 1) / s_ts;
    int r0 = s_view_y / s_ts;
    int r1 = (s_view_y + ALBUM_VIEW - 1) / s_ts;
    if (c0 > 0) c0--;
    if (r0 > 0) r0--;
    if (c1 < s_tcols - 1) c1++;
    if (r1 < s_trows - 1) r1++;

    /* Same tile window as the previous call -> only reposition, skip the
     * SD load/unload (called on every PRESSING sample while panning).
     * "has_tiles" guards the first call after (re-)entering 1:1 so a
     * coincidentally equal window can never skip the initial load. */
    static int last_c0 = -1, last_c1 = -1, last_r0 = -1, last_r1 = -1;
    bool has_tiles = false;
    for (int i = 0; i < ALBUM_TILE_MAX; i++) {
        if (s_tiles[i].used) { has_tiles = true; break; }
    }
    if (has_tiles && last_c0 == c0 && last_c1 == c1 && last_r0 == r0 && last_r1 == r1) {
        for (int i = 0; i < ALBUM_TILE_MAX; i++) {
            if (!s_tiles[i].used) continue;
            lv_obj_set_pos(s_tiles[i].img,
                           s_tiles[i].c * s_ts - s_view_x,
                           s_tiles[i].r * s_ts - s_view_y);
        }
        return;
    }
    last_c0 = c0;
    last_c1 = c1;
    last_r0 = r0;
    last_r1 = r1;

    for (int i = 0; i < ALBUM_TILE_MAX; i++) {
        if (!s_tiles[i].used) continue;
        if (s_tiles[i].c < c0 || s_tiles[i].c > c1 ||
            s_tiles[i].r < r0 || s_tiles[i].r > r1) {
            _tile_unload(&s_tiles[i]);
        }
    }
    for (int c = c0; c <= c1; c++) {
        for (int r = r0; r <= r1; r++) {
            if (!_tile_find(c, r)) _tile_load(c, r);
        }
    }
    for (int i = 0; i < ALBUM_TILE_MAX; i++) {
        if (!s_tiles[i].used) continue;
        lv_obj_set_pos(s_tiles[i].img,
                       s_tiles[i].c * s_ts - s_view_x,
                       s_tiles[i].r * s_ts - s_view_y);
    }
}

static void _tile_exit(void);

static void _tile_enter(int tap_x, int tap_y)
{
    if (s_tile_mode || s_count <= 0) return;

    char dir[ALBUM_PATH_BUF], mpath[ALBUM_PATH_BUF];
    _tiles_dir(s_paths[s_index], dir, sizeof(dir));
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wformat-truncation"
    snprintf(mpath, sizeof(mpath), "%s/meta.txt", dir);
#pragma GCC diagnostic pop
    char *meta = eos_storage_read_file(mpath);
    if (!meta) {
        _show_msg("NO HD DATA\nRun album_optimize.py");
        return;
    }
    int ow = 0, oh = 0, ts = 0, cols = 0, rows = 0;
    int parsed = sscanf(meta, "%d %d %d %d %d", &ow, &oh, &ts, &cols, &rows);
    eos_free(meta);
    if (parsed != 5 || ts <= 0 || cols <= 0 || rows <= 0 || ow <= 0 || oh <= 0) {
        _show_msg("NO HD DATA\nRun album_optimize.py");
        return;
    }
    /* 1:1 on an image no bigger than the viewport is pointless */
    if (ow <= ALBUM_VIEW && oh <= ALBUM_VIEW) return;

    s_orig_w = ow;
    s_orig_h = oh;
    s_tcols  = cols;
    s_trows  = rows;
    s_ts     = ts;

    /* fullscreen canvas above the buttons */
    s_canvas = lv_obj_create(s_root);
    lv_obj_remove_style_all(s_canvas);
    lv_obj_set_size(s_canvas, ALBUM_VIEW, ALBUM_VIEW);
    lv_obj_set_pos(s_canvas, 0, 0);
    lv_obj_remove_flag(s_canvas, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_add_flag(s_canvas, LV_OBJ_FLAG_CLICKABLE);
    lv_obj_add_event_cb(s_canvas, _img_event_cb, LV_EVENT_PRESSED, NULL);
    lv_obj_add_event_cb(s_canvas, _img_event_cb, LV_EVENT_PRESSING, NULL);
    lv_obj_add_event_cb(s_canvas, _img_event_cb, LV_EVENT_RELEASED, NULL);

    s_tile_badge = lv_label_create(s_root);
    lv_obj_set_style_text_color(s_tile_badge, lv_color_hex(_UI_TEXT), 0);
    lv_obj_set_style_text_font(s_tile_badge, &lv_font_montserrat_12, 0);
    lv_label_set_text(s_tile_badge, "1:1");
    lv_obj_align(s_tile_badge, LV_ALIGN_TOP_RIGHT, -8, 24);

    /* hide chrome, start at image center */
    _ui_controls(false);
    lv_obj_add_flag(s_img, LV_OBJ_FLAG_HIDDEN);
    s_tile_mode = true;

    /* Tap-where-you-zoom: map the tap point (screen coords) through the
     * fitted thumbnail rectangle into original-image pixels and centre the
     * viewport there (clamped to the image bounds). Falls back to centre. */
    int ox = ow / 2, oy = oh / 2;
    if (s_img_w > 0 && s_img_h > 0) {
        uint32_t sc = _fit_scale(s_img_w, s_img_h);
        int wd = (int)((s_img_w * sc) >> 8);   /* on-screen size */
        int hd = (int)((s_img_h * sc) >> 8);
        if (wd > 0 && hd > 0) {
            int rx = tap_x - (ALBUM_VIEW - wd) / 2;
            int ry = tap_y - (ALBUM_VIEW - hd) / 2;
            if (rx < 0) rx = 0;
            else if (rx > wd) rx = wd;
            if (ry < 0) ry = 0;
            else if (ry > hd) ry = hd;
            ox = (rx * ow + wd / 2) / wd;      /* round to nearest px */
            oy = (ry * oh + hd / 2) / hd;
        }
    }
    int mx = ow - ALBUM_VIEW, my = oh - ALBUM_VIEW;
    if (mx < 0) mx = 0;
    if (my < 0) my = 0;
    s_view_x = ox - ALBUM_VIEW / 2;
    s_view_y = oy - ALBUM_VIEW / 2;
    if (s_view_x < 0) s_view_x = 0;
    if (s_view_x > mx) s_view_x = mx;
    if (s_view_y < 0) s_view_y = 0;
    if (s_view_y > my) s_view_y = my;
    _tile_refresh();
    EOS_LOG_I("Album: 1:1 %dx%d grid %dx%d ts=%d view=%d,%d",
              ow, oh, cols, rows, ts, s_view_x, s_view_y);
}

static void _tile_exit(void)
{
    if (!s_tile_mode && !s_canvas) return;
    s_tile_mode = false;
    for (int i = 0; i < ALBUM_TILE_MAX; i++) _tile_unload(&s_tiles[i]);
    if (s_canvas) {
        lv_obj_delete(s_canvas);
        s_canvas = NULL;
    }
    if (s_tile_badge) {
        lv_obj_delete(s_tile_badge);
        s_tile_badge = NULL;
    }
    _ui_controls(true);
    lv_obj_remove_flag(s_img, LV_OBJ_FLAG_HIDDEN);
    if (s_img_w > 0) _apply_view();
}


/**
 * @file eos_config_defaults.h
 * @brief Kernel default configuration values
 *
 * This file provides FALLBACK defaults for every configurable option.
 * It uses the #ifndef pattern – if a value has already been set by
 * any platform layer (generated header, -D flag, eos_platform_config.h),
 * the default is skipped.
 *
 * This header knows NOTHING about CONFIG_ prefixes or any specific
 * Kconfig system.  It is purely a fallback-defaults provider.
 *
 * Override priority (highest to lowest):
 *   1. Compiler -D flags (e.g. CPPDEFINES)
 *   2. eos_platform_config.h       (manual, project-specific)
 *   3. eos_config_gen.h            (generated by a Kconfig system)
 *   4. This file                   (kernel fallback defaults)
 */


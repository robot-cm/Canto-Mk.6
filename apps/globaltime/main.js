// ===================== 投影与渲染 =====================
var theta = 0;
var DOT = [];
for (var di = 0; di < 400; di++) { DOT.push(null); }

R.active = 0;                              // 当前激活点数（swapDots 维护）
R.Z = 1;                                   // 当前缩放（1=正交全局，Zt=聚焦特写）
R.Zt = 1;                                  // 目标聚焦缩放
R.bboxLat0 = 0;                            // 当前 dots 数据地理中心
R.bboxLon0 = 0;
R.span = 1;
function bboxCenter(dots, refLon) {
    var minLat = 90, maxLat = -90;
    var n = Math.min(dots.length, 400);
    var minD = 180, maxD = -180;
    for (var j = 0; j < n; j++) {
        var la = dots[j][0], lo = dots[j][1];
        if (la < minLat) { minLat = la; }
        if (la > maxLat) { maxLat = la; }
        var d = ((lo - refLon + 540) % 360) - 180;   // 经度卷绕到 refLon 附近（跨日界线安全）
        if (d < minD) { minD = d; }
        if (d > maxD) { maxD = d; }
    }
    return { lat0: (minLat + maxLat) / 2, lon0: refLon + (minD + maxD) / 2 };
}

function swapDots(dots, refLon) {
    if (refLon === undefined) { refLon = 0; }      // GLOBAL 缺省 0
    R.active = Math.min(dots.length, 400);
    for (var i = 0; i < 400; i++) {
        DOT[i] = (i < R.active) ? dots[i] : null;    // i>=active 一律 null
    }
    // bbox：中心（refLon 卷绕）+ span，聚焦缩放 Zt=clamp(90/span, 1, 140)
    var bc = bboxCenter(dots, refLon);
    R.bboxLat0 = bc.lat0;
    R.bboxLon0 = bc.lon0;
    var minLat = 90, maxLat = -90, minD = 180, maxD = -180;
    for (var j = 0; j < R.active; j++) {
        var la = dots[j][0], lo = dots[j][1];
        if (la < minLat) { minLat = la; }
        if (la > maxLat) { maxLat = la; }
        var d = ((lo - refLon + 540) % 360) - 180;
        if (d < minD) { minD = d; }
        if (d > maxD) { maxD = d; }
    }
    var dLat = maxLat - minLat;
    var dLon = maxD - minD;                        // 卷绕后跨度（跨日界线安全）
    var span = Math.max(dLat, dLon * Math.cos(R.bboxLat0 * Math.PI / 180));
    if (span <= 0) { span = 1; }
    R.span = span;
    var zt = 90 / span;
    if (zt < 1) { zt = 1; }
    if (zt > 140) { zt = 140; }
    R.Zt = zt;
}

function projectDot(p, lat, lon, updateOpa) {
    if (state === S.FOCUS) {
        // 局部切面投影（特写）：K=R·π/180；球面裁切 (R-2)²
        var K = RADIUS * Math.PI / 180;
        var dl = ((lon - theta) % 360 + 540) % 360 - 180;      // 经度差归一
        var x = CX + R.Z * K * dl * Math.cos(R.bboxLat0 * Math.PI / 180);
        var y = CY - R.Z * K * (lat - R.bboxLat0);
        var dx = x - CX, dy = y - CY;
        if (dx * dx + dy * dy > (RADIUS - 2) * (RADIUS - 2)) { p.addFlag(lv.OBJ_FLAG_HIDDEN); return; }
        p.setSize(2, 2);                                       // 特写：2×2 + 全 255（点小更精致）
        p.setStyleBgOpa(255, 0);
        p.setPos(Math.round(x) - 1, Math.round(y) - 1);
        p.removeFlag(lv.OBJ_FLAG_HIDDEN);
        return;
    }
    // 正交投影（全局浏览 Z=1）
    var lam = (lon - theta) * Math.PI / 180;
    var phi = lat * Math.PI / 180;
    var z = Math.cos(phi) * Math.cos(lam);
    if (z <= 0.02) { p.addFlag(lv.OBJ_FLAG_HIDDEN); return; }
    var x = CX + RADIUS * Math.cos(phi) * Math.sin(lam);
    var y = CY - RADIUS * Math.sin(phi);
    p.setSize(1, 1);                                           // 浏览：1×1 + 深度感（小点密集）
    p.setPos(Math.round(x) - 1, Math.round(y) - 1);
    if (updateOpa) { p.setStyleBgOpa(Math.round(60 + 190 * z), 0); }
    p.removeFlag(lv.OBJ_FLAG_HIDDEN);
}

// 城市点/声纳共用：返回 {x,y} 或 null（不可见）
function cityScreenPos(lat, lon) {
    if (state === S.FOCUS) {
        var K = RADIUS * Math.PI / 180;
        var dl = ((lon - theta) % 360 + 540) % 360 - 180;
        var x = CX + R.Z * K * dl * Math.cos(R.bboxLat0 * Math.PI / 180);
        var y = CY - R.Z * K * (lat - R.bboxLat0);
        var dx = x - CX, dy = y - CY;
        if (dx * dx + dy * dy > (RADIUS - 2) * (RADIUS - 2)) { return null; }
        return { x: x, y: y };
    }
    var lam = (lon - theta) * Math.PI / 180;
    var phi = lat * Math.PI / 180;
    var z = Math.cos(phi) * Math.cos(lam);
    if (z <= 0.02) { return null; }
    return { x: CX + RADIUS * Math.cos(phi) * Math.sin(lam), y: CY - RADIUS * Math.sin(phi) };
}

